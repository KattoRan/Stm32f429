void swap_int(int *a, int *b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

void ILI9341_DrawFilledTriangle(int x0, int y0,
                                int x1, int y1,
                                int x2, int y2,
                                uint16_t color) {
    // Sort vertices by y-coordinate ascending (y0 <= y1 <= y2)
    if (y0 > y1) { swap_int(&y0, &y1); swap_int(&x0, &x1); }
    if (y1 > y2) { swap_int(&y2, &y1); swap_int(&x2, &x1); }
    if (y0 > y1) { swap_int(&y0, &y1); swap_int(&x0, &x1); }

    int total_height = y2 - y0;
    for (int i = 0; i < total_height; i++) {
        int second_half = i > y1 - y0 || y1 == y0;
        int segment_height = second_half ? y2 - y1 : y1 - y0;

        float alpha = (float)i / total_height;
        float beta = (float)(i - (second_half ? y1 - y0 : 0)) / segment_height;

        int ax = x0 + (x2 - x0) * alpha;
        int bx = second_half
                 ? x1 + (x2 - x1) * beta
                 : x0 + (x1 - x0) * beta;

        if (ax > bx) swap_int(&ax, &bx);
        for (int j = ax; j <= bx; j++) {
            ILI9341_DrawPixel(j, y0 + i, color);
        }
    }
}


void drawStar(int x, int y, int radius, uint16_t color) {
    float angle = PI / 2; // Start pointing upwards
    int points[10][2];

    // Calculate points for a 5-pointed star
    // Making the inner radius smaller will create a thinner star
    float innerRadiusRatio = 0.38; // Reduced from 0.5 to make star thinner

    for (int i = 0; i < 10; i++) {
        float r = (i % 2 == 0) ? radius : radius * innerRadiusRatio;
        points[i][0] = x + r * cos(angle);
        points[i][1] = y - r * sin(angle);
        angle += PI / 5;
    }

    // Draw the star using triangles from the center point
    for (int i = 0; i < 10; i++) {
        int next = (i + 1) % 10;
        ILI9341_DrawFilledTriangle(
            x, y,                      // Center of star
            points[i][0], points[i][1], // Current point
            points[next][0], points[next][1], // Next point
            color
        );
    }
}
